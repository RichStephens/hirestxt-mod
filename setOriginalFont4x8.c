/*  setOriginalFont4x8.c - picks which glyphs characters 160-185 of the
    4x8 font carry: the line-drawing set or the ISO-8859-1 originals.

    One table serves both directions. It holds whichever set is not
    currently live in font4x8[], and the two are exchanged in place, so
    switching costs 208 bytes rather than the 416 two tables would need.

    In its own file so a program that never calls this links neither the
    table nor font4x8[] itself.

    This file is in the public domain.
*/

#include "hirestxt.h"
#include "font4x8.h"


